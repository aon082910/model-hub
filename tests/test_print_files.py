def test_a_finished_print_of_a_kept_file_logs_its_estimated_filament(authed, model, printer):
    fake, p = printer
    f = _upload(authed, model["id"], "benchy.gcode").json()
    authed.post(f"/api/printers/{p['id']}/send", data={"print_file_id": str(f["id"]), "start": "true"})
    from sqlmodel import Session
    from app.db import engine
    with Session(engine) as s:
        fake.moonraker_state = "printing"
        printwatch.poll(s)
        fake.moonraker_state = "complete"
        assert printwatch.poll(s) == [("Kept", "done")]
    log = authed.get("/api/prints", params={"model_id": model["id"]}).json()["items"][0]
    assert log["grams"] == 12.94 and log["source"] == "printer"
