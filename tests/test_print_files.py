def test_deleting_a_file_or_its_model_removes_it_from_disk(authed):
    m = authed.post("/api/library/import", files={"file": ("pf_gone.stl", _stl(171), "application/octet-stream")}).json()
    a = _upload(authed, m["id"]).json()
    b = _upload(authed, m["id"], "second.gcode", b"G28\n; layer_height = 0.25\n").json()
    from sqlmodel import Session, select
    from app.db import engine
    from app.models import PrintFile
    with Session(engine) as s:
        stored = {r.id: r.stored_name for r in s.exec(select(PrintFile).where(PrintFile.model_id == m["id"])).all()}
    assert all(print_files.stored_path(n).is_file() for n in stored.values())
    assert authed.delete(f"/api/print-files/{a['id']}").status_code == 200
    assert not print_files.stored_path(stored[a["id"]]).exists() and print_files.stored_path(stored[b["id"]]).is_file()
    assert authed.delete(f"/api/print-files/{a['id']}").status_code == 404
    authed.delete(f"/api/library/models/{m['id']}")
    assert not print_files.stored_path(stored[b["id"]]).exists()
    assert authed.get(f"/api/print-files/{b['id']}/download").status_code == 404


