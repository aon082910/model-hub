def test_a_kept_file_is_sent_to_a_printer_and_remembered(authed, model, printer):
    fake, p = printer
    f = _upload(authed, model["id"], "My Part v3.gcode").json()
    r = authed.post(f"/api/printers/{p['id']}/send", data={"print_file_id": str(f["id"]), "start": "false"})
    assert r.status_code == 200, r.text
    assert r.json() == {"filename": "My_Part_v3.gcode", "started": False}
    assert b"G28" in fake.uploads[0][1]
    from sqlmodel import Session, select
    from app.db import engine
    from app.models import PrinterJob
    with Session(engine) as s:
        job = s.exec(select(PrinterJob).where(PrinterJob.print_file_id == f["id"])).first()
        assert job and job.model_id == model["id"]


