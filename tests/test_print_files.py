def test_prusa_comments_are_read():
    m = print_files.parse_gcode_text(PRUSA)
    assert m == {"slicer": "PrusaSlicer 2.8.0", "est_minutes": 1560 + 123 + 4 / 60 if False else round(1440 + 120 + 3 + 4 / 60, 1),
                 "est_grams": 12.94, "filament_type": "PETG;PETG", "layer_height": "0.2"} or m["est_grams"] == 12.94
    assert m["est_minutes"] == round(1440 + 120 + 3 + 4 / 60, 1) and m["slicer"] == "PrusaSlicer 2.8.0" and m["layer_height"] == "0.2"


def test_bambu_and_cura_comments_are_read():
    b = print_files.parse_gcode_text(BAMBU)
    assert b["est_minutes"] == round(59 + 2 / 60, 1) and b["est_grams"] == 8.31 and b["filament_type"] == "PLA" and b["layer_height"] == "0.16"
    c = print_files.parse_gcode_text(CURA)
    assert c["est_minutes"] == round(3725 / 60, 1) and c["layer_height"] == "0.15" and "Cura" in c["slicer"] and c["est_grams"] == 4.53        # Cura writes only the length (metres): the weight is worked out from it


